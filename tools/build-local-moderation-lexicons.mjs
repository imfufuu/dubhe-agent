import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lexiconRoot = path.join(root, 'assets/moderation/lexicons');
const outputPath = path.join(root, 'js/local-moderation-lexicons.js');
const ZERO_WIDTH = /[\u200b-\u200f\u202a-\u202e\u2060-\u206f\ufeff]/gu;
const MARKS = /\p{M}+/gu;

function normalize(value) {
  let text = String(value ?? '');
  try { text = text.normalize('NFKD'); } catch { /* old runtimes */ }
  return text.toLowerCase().replace(MARKS, '').replace(ZERO_WIDTH, '')
    .replace(/[0０]/gu, 'o').replace(/[1１!！|]/gu, 'i').replace(/[3３]/gu, 'e')
    .replace(/[4４@]/gu, 'a').replace(/[5５$]/gu, 's')
    .replace(/[^\p{L}\p{N}]+/gu, ' ').replace(/\s+/gu, ' ').trim();
}

async function readWordFiles(directory, omit = new Set()) {
  const entries = await readdir(directory, { withFileTypes: true });
  const terms = [];
  for (const entry of entries) {
    if (!entry.isFile() || omit.has(entry.name)) continue;
    const raw = await readFile(path.join(directory, entry.name), 'utf8');
    if (entry.name.toLowerCase().endsWith('.csv')) {
      // Both upstream CSV collections are one vocabulary item per row (including quoted rows).
      for (const row of raw.split(/\r?\n/u)) {
        const value = row.trim().replace(/^"|"$/gu, '').replace(/""/gu, '"');
        if (value) terms.push(value);
      }
    } else {
      for (const row of raw.split(/\r?\n/u)) if (row.trim()) terms.push(row.trim());
    }
  }
  return terms;
}

const ldnoobwTerms = await readWordFiles(path.join(lexiconRoot, 'ldnobw'), new Set(['LICENSE', 'README.md', 'USERS.md']));
const fourtroTerms = await readWordFiles(path.join(lexiconRoot, '4tro'), new Set(['LICENSE', 'README.md']));
const cnWeaponTerms = (await readFile(path.join(lexiconRoot, 'konsheng/涉枪涉爆.txt'), 'utf8'))
  .split(/\r?\n/u).map((term) => normalize(term)).filter(Boolean);
const normalized = new Set();
for (const term of [...ldnoobwTerms, ...fourtroTerms]) {
  const value = normalize(term);
  if ([...value.replace(/\s/gu, '')].length < 2) continue;
  normalized.add(value);
}

const exactTerms = [];
const substringTerms = [];
for (const term of normalized) {
  const compact = term.replace(/\s/gu, '');
  const hasUnsegmentedScript = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}\p{Script=Thai}]/u.test(term);
  if (hasUnsegmentedScript && [...compact].length >= 2) substringTerms.push(compact);
  exactTerms.push(term);
}
exactTerms.sort();
substringTerms.sort();

const sourceStats = {
  ldnoobwFiles: (await readdir(path.join(lexiconRoot, 'ldnobw'))).filter((name) => !['LICENSE', 'README.md', 'USERS.md'].includes(name)).length,
  fourtroFiles: (await readdir(path.join(lexiconRoot, '4tro'))).filter((name) => name.endsWith('.csv')).length,
  sourceEntries: ldnoobwTerms.length + fourtroTerms.length,
  normalizedTerms: normalized.size,
  cnWeaponExplosivePhrases: cnWeaponTerms.length,
  sourceLanguageFiles: 40,
};

const generated = `// Generated by tools/build-local-moderation-lexicons.mjs; do not edit by hand.\n// Source licenses and pinned commits: assets/moderation/lexicons/THIRD-PARTY-NOTICES.md\nconst EXACT_TERMS = new Set(${JSON.stringify(exactTerms)});\nconst UNSEGMENTED_TERMS = new Set(${JSON.stringify(substringTerms)});\nexport const CN_WEAPON_EXPLOSIVE_TERMS = Object.freeze(${JSON.stringify(cnWeaponTerms)});\n\nexport const LOCAL_PROFANITY_LEXICON_STATS = Object.freeze(${JSON.stringify(sourceStats)});\n\n// The broad upstream dictionaries are only applied to a short, strict salutation field.\n// Ordinary message moderation continues to require the contextual local policy rules.\nexport function hasExternalProfanity(input) {\n  const words = String(input?.words || '').split(/\\s+/u).filter(Boolean);\n  for (let start = 0; start < words.length; start++) {\n    let phrase = '';\n    for (let end = start; end < words.length && end < start + 8; end++) {\n      phrase = phrase ? phrase + ' ' + words[end] : words[end];\n      if (EXACT_TERMS.has(phrase)) return true;\n    }\n  }\n  const chars = [...String(input?.compact || '')].slice(0, 64);\n  for (let start = 0; start < chars.length; start++) {\n    let candidate = '';\n    for (let end = start; end < chars.length && end < start + 16; end++) {\n      candidate += chars[end];\n      if (candidate.length >= 2 && UNSEGMENTED_TERMS.has(candidate)) return true;\n    }\n  }\n  return false;\n}\n`;
await writeFile(outputPath, generated, 'utf8');
console.log(`Wrote ${path.relative(root, outputPath)} (${sourceStats.normalizedTerms} normalized terms; ${sourceStats.ldnoobwFiles} LDNOOBW and ${sourceStats.fourtroFiles} 4tro files).`);
